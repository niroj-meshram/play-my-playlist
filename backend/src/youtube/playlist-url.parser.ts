import { HttpStatus } from '@nestjs/common';
import { ErrorCode } from '@pmp/shared';
import { AppException } from '../common/errors/app.exception.js';

const YOUTUBE_HOSTS = new Set([
  'youtube.com',
  'www.youtube.com',
  'm.youtube.com',
  'music.youtube.com',
  'youtu.be',
  'www.youtu.be',
]);

/** YouTube playlist IDs: URL-safe base64 characters (PL…, OLAK5uy_…, UU…, etc.). */
const PLAYLIST_ID_PATTERN = /^[A-Za-z0-9_-]{2,64}$/;

const CURATED_MUSIC_PREFIX = 'RDCLAK5uy_';

/** Personal or generated lists the Data API cannot read for other users. */
const UNSUPPORTED: { test: (id: string) => boolean; message: string }[] = [
  {
    test: (id) => id === 'LL' || id === 'LM',
    message: 'Your Liked videos list is private to you. Copy the songs into a regular playlist.',
  },
  {
    test: (id) => id === 'WL',
    message: 'Watch Later is private to you. Copy the songs into a regular playlist.',
  },
  {
    // RD… are per-user generated mixes, except YouTube Music's curated RDCLAK5uy_… playlists,
    // which the Data API serves like any public playlist.
    test: (id) => id.startsWith('RD') && !id.startsWith(CURATED_MUSIC_PREFIX),
    message: 'Mixes are generated by YouTube and cannot be read. Please share a regular playlist.',
  },
];

/**
 * Extracts the playlist ID from a YouTube or YouTube Music URL, or accepts a bare ID.
 * Throws `INVALID_PLAYLIST_URL` or `UNSUPPORTED_PLAYLIST` (400) with a user-facing message.
 */
export function parsePlaylistId(input: string): string {
  const value = input.trim();
  const id = PLAYLIST_ID_PATTERN.test(value) ? value : fromUrl(value);

  if (!id || !PLAYLIST_ID_PATTERN.test(id)) {
    throw new AppException(
      ErrorCode.INVALID_PLAYLIST_URL,
      'That does not look like a YouTube playlist link. Open the playlist and copy its URL.',
      HttpStatus.BAD_REQUEST,
    );
  }
  const unsupported = UNSUPPORTED.find((rule) => rule.test(id));
  if (unsupported) {
    throw new AppException(
      ErrorCode.UNSUPPORTED_PLAYLIST,
      unsupported.message,
      HttpStatus.BAD_REQUEST,
    );
  }
  return id;
}

function fromUrl(value: string): string | null {
  let url: URL;
  try {
    url = new URL(/^https?:\/\//i.test(value) ? value : `https://${value}`);
  } catch {
    return null;
  }
  if (!YOUTUBE_HOSTS.has(url.hostname.toLowerCase())) return null;
  return url.searchParams.get('list');
}
